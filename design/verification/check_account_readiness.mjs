// Real production UI + API + PostgreSQL. Run only against the disposable readiness server.
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from './browser.mjs'
assert.equal(process.env.POMOGIT_READINESS_DISPOSABLE, 'true', 'Requires a disposable database/backend')
const base = 'http://127.0.0.1:5174'
const output = '/tmp/pomogit-account-readiness'
await mkdir(output, { recursive: true })
const checks = []
const browser = await chromium.launch({ args: ['--disable-dev-shm-usage'] })
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } })
    let page = await context.newPage()
    const errors = []
    const watch = () => page.on('pageerror', error => errors.push(error.message))
    watch()
    const check = (name, condition) => { assert(condition, name); checks.push({ width, name }); console.log(`${width}: ${name}`) }
    const email = `${randomUUID()}@readiness-test.invalid`, password = randomUUID()
    const login = async () => {
      await page.goto(`${base}/#login`)
      await page.locator('[name=email]').fill(email)
      await page.locator('[name=password]').fill(password)
      await page.locator('.pg-account-form button[type=submit]').click()
      await page.locator('.dash-heading').waitFor()
    }
    const logout = async () => {
      const dismiss = page.getByRole('button', { name: 'Dismiss notification' })
      if (await dismiss.isVisible()) await dismiss.click()
      await page.locator('.wb-account-menu summary').click()
      await page.getByRole('button', { name: 'Log out', exact: true }).click()
      const confirmation = page.getByRole('dialog')
      if (await confirmation.isVisible()) await confirmation.getByRole('button', { name: 'Log out', exact: true }).click()
      await page.locator('.pg-account-form').waitFor()
    }
    await page.goto(`${base}/#tasks`)
    await page.locator('.pg-account-form').waitFor()
    check('Unauthenticated Board requires login', page.url().endsWith('#login'))
    await page.goto(`${base}/#register`)
    await page.locator('[name=email]').fill(email)
    await page.locator('[name=password]').fill(password)
    await page.locator('.pg-account-form button[type=submit]').click()
    await page.locator('.dash-empty').waitFor()
    check('Registration opens empty Home with HttpOnly cookie', (await context.cookies()).some(c => c.name === 'pomogit_session' && c.httpOnly))
    await page.getByRole('button', { name: 'New task', exact: true }).click()
    await page.getByRole('textbox', { name: 'Task title or reference link' }).fill('Verify account persistence')
    await page.getByRole('button', { name: 'Create task', exact: true }).click()
    await page.locator('.wb-detail').waitFor()
    await page.locator('.wb-task-actions').getByRole('button', { name: 'Edit', exact: true }).click()
    await page.locator('#wb-edit-task [name=project]').fill('readiness-check')
    await page.locator('#wb-edit-task [name=nextStep]').fill('Resume after signing in again')
    await page.locator('#wb-edit-task [name=note]').fill('Saved context survives another browser')
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Start focus', exact: true }).click()
    await page.locator('.wb-focus[data-state=running]').waitFor()
    await page.waitForTimeout(1200)
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    await page.locator('.wb-focus[data-state=paused]').waitFor()
    await page.reload()
    await page.locator('.wb-focus[data-state=paused]').waitFor()
    check('Reload restores notes and paused focus', (await page.locator('.wb-detail').innerText()).includes('Saved context survives another browser'))
    const oldCookie = (await context.cookies()).find(c => c.name === 'pomogit_session')
    await logout()
    const revoked = await context.request.get(`${base}/api/auth/me`, { headers: { Cookie: `${oldCookie.name}=${oldCookie.value}` } })
    check('Logout revokes the previous opaque session', revoked.status() === 401)
    await context.close()
    // A fresh browser has neither account cookies nor workspace local storage.
    const fresh = await browser.newContext({ viewport: { width, height: 900 } })
    page = await fresh.newPage(); watch()
    await login()
    await page.goto(`${base}/#work`)
    await page.locator('.wb-focus[data-state=paused]').waitFor()
    check('Fresh browser restores project, next step and notes', (await page.locator('.wb-detail').innerText()).includes('readiness-check') && (await page.locator('.wb-next-step').innerText()).includes('signing in again'))
    await page.getByRole('button', { name: 'Resume', exact: true }).click()
    await page.locator('.wb-focus[data-state=running]').waitFor()
    await page.waitForTimeout(1200)
    await page.getByRole('button', { name: 'Stop timer', exact: true }).click()
    await page.locator('.wb-focus[data-state=ready]').waitFor()
    await page.getByRole('button', { name: 'Mark done', exact: true }).click()
    await page.getByRole('dialog', { name: 'Task completed', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Back to Workspace', exact: true }).click()
    const response = await fresh.request.get(`${base}/api/export`)
    const snapshot = await response.json()
    check('Completion persists task, notes and ended focus history', response.ok() && snapshot.tasks[0].status === 'done' && snapshot.tasks[0].project === 'readiness-check' && snapshot.tasks[0].notes.some(note => note.text === 'Saved context survives another browser') && snapshot.focusSessions[0].status === 'ended' && snapshot.focusSessions[0].durationActualSeconds >= 1)
    await page.goto(`${base}/#home`)
    await page.locator('.dash-heading').waitFor()
    // Only the failure is injected; retry uses the actual backend.
    await page.route('**/api/sessions', route => route.abort())
    await page.reload()
    await page.getByRole('button', { name: 'Try again', exact: true }).waitFor()
    check('History failure offers retry instead of fabricated figures', (await page.locator('main').innerText()).includes('Work history couldn’t load'))
    await page.unroute('**/api/sessions')
    await page.getByRole('button', { name: 'Try again', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('main')?.textContent.includes('Work history couldn’t load'))
    await page.screenshot({ path: `${output}/home-${width}.png`, fullPage: true })
    check('Retry restores real Home without horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    if (width === 1440 && process.env.POMOGIT_READINESS_REPOSITORY) {
      await page.goto(`${base}/#tasks`)
      await page.getByRole('button', { name: 'Manage projects', exact: true }).click()
      await page.locator('.wb-repo-connect summary').click()
      await page.locator('[name=repository]').fill(process.env.POMOGIT_READINESS_REPOSITORY)
      await page.getByRole('button', { name: 'Connect repository', exact: true }).click()
      const firstIssue = page.locator('.wb-github-issue').first()
      await firstIssue.waitFor()
      const number = Number((await firstIssue.locator('small').innerText()).match(/#(\d+)/)[1])
      await firstIssue.getByRole('checkbox').check()
      await page.getByRole('button', { name: 'Import 1 selected into Inbox', exact: true }).click()
      await page.getByRole('dialog').waitFor({ state: 'hidden' })
      const projects = await (await fresh.request.get(`${base}/api/github/projects`)).json()
      const project = projects.find(item => item.fullName.toLowerCase() === process.env.POMOGIT_READINESS_REPOSITORY.toLowerCase())
      assert(project, 'Live repository connection is saved')
      const repeat = await fresh.request.post(`${base}/api/github/projects/${project.id}/import`, { data: { numbers: [number] }, headers: { Origin: base } })
      const result = await repeat.json()
      check('Live GitHub issue imports once and repeat is skipped', repeat.ok() && result.imported === 0 && result.skipped === 1)
      const tasks = await (await fresh.request.get(`${base}/api/tasks`)).json()
      check('Live import persists one Inbox task with GitHub reference', tasks.filter(task => task.project === project.fullName).length === 1 && tasks.some(task => task.project === project.fullName && task.status === 'inbox' && task.referenceUrl.endsWith(`/issues/${number}`)))
      await page.screenshot({ path: `${output}/live-import.png`, fullPage: true })
    }
    check('No uncaught JavaScript errors', errors.length === 0)
    await fresh.close()
  }
  await writeFile(`${output}/results.json`, JSON.stringify({ checks }, null, 2))
  console.log(`${checks.length} real-account browser checks passed; evidence: ${output}`)
} finally { await browser.close() }
